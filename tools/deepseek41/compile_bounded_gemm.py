"""Offline SM120 cubins; Triton is a build tool, never a serving dependency.

Own bounded-pointer-array GEMM using BF16 operands and FP32 dot accumulation.
Packed quant formats remain the existing native dequantizers. No routing, SiLU,
weight conversion or other vLLM-specific numerical semantics are imported.
"""
from pathlib import Path
import hashlib,json,os,re
from sanitize_cubin import sanitize
import triton
import triton.language as tl
from triton.compiler import ASTSource
from triton.backends.compiler import GPUTarget

@triton.jit
def bounded_grouped_bf16(WP,XP,YP,Rows,Count,
                         N:tl.constexpr,K:tl.constexpr,BM:tl.constexpr,BN:tl.constexpr,BK:tl.constexpr):
    block=tl.program_id(0);pn=block%tl.cdiv(N,BN);pm=block//tl.cdiv(N,BN)
    expert=0;nrows=tl.load(Rows);blocks=tl.cdiv(nrows,BM)
    while pm>=blocks and expert+1<Count:
        pm-=blocks;expert+=1;nrows=tl.load(Rows+expert);blocks=tl.cdiv(nrows,BM)
    w=tl.load(WP+expert).to(tl.pointer_type(tl.bfloat16))
    x=tl.load(XP+expert).to(tl.pointer_type(tl.bfloat16))
    y=tl.load(YP+expert).to(tl.pointer_type(tl.bfloat16))
    w=tl.multiple_of(w,16);x=tl.multiple_of(x,16);y=tl.multiple_of(y,16)
    rm=pm*BM+tl.arange(0,BM);rn=pn*BN+tl.arange(0,BN);rk=tl.arange(0,BK)
    ap=x+rm[:,None]*K+rk[None,:];bp=w+rn[None,:]*K+rk[:,None]
    acc=tl.full((BM,BN),0,tl.float32)
    for _ in range(tl.cdiv(K,BK)):
        a=tl.load(ap,rm[:,None]<nrows,0)
        b=tl.load(bp,rn[None,:]<N,0)
        acc=tl.dot(a,b,acc)
        ap+=BK;bp+=BK
    tl.store(y+rm[:,None]*N+rn[None,:],acc.to(tl.bfloat16),(rm[:,None]<nrows)&(rn[None,:]<N))

def main():
    root=Path(__file__).resolve().parents[2];out=root/'src/kernels/cuda/bounded_gemm_generated.cuh'
    variants=[(64,128,32,4,3)]
    lines=['// Generated by tools/deepseek41/compile_bounded_gemm.py; do not edit.','#pragma once']
    metadata=[]
    for variant,(bm,bn,bk,warps,stages) in enumerate(variants):
        for projection,(n,k) in enumerate([(4608,5120),(5120,2304)]):
            source=ASTSource(bounded_grouped_bf16,{'WP':'*u64','XP':'*u64','YP':'*u64','Rows':'*i32','Count':'i32'},
                constexprs={'N':n,'K':k,'BM':bm,'BN':bn,'BK':bk})
            result=triton.compile(source,target=GPUTarget('cuda',120,32),options={'num_warps':warps,'num_stages':stages,'enable_fp_fusion':True})
            cubin=sanitize(result.asm['cubin']);ident=f'bounded_cubin_{variant}_{projection}'
            ptx=re.sub(r'(?m)^(\s*\.file\s+\d+\s+")[^"]*(/[^/"\n]+)"',
                       lambda m: m[1]+m[2].lstrip('/')+'"',result.asm['ptx'])
            (out.parent/(ident+'.ptx')).write_text(ptx)
            lines.append(f'alignas(16) static const unsigned char {ident}[]={{')
            lines.extend(','.join(str(b) for b in cubin[i:i+24])+',' for i in range(0,len(cubin),24));lines.append('};')
            m=result.metadata
            metadata.append(dict(variant=variant,projection=projection,m=bm,n=bn,k=bk,warps=warps,stages=stages,shared=m.shared,name=m.name,cubin_bytes=len(cubin),sha256=hashlib.sha256(cubin).hexdigest(),compiler=triton.__version__,target='sm120',gpu_executed=False))
            print(ident,len(cubin),m.shared,flush=True)
    lines.append('struct BoundedCubin {const unsigned char* data;const char* name;int bm,bn,warps,shared;};')
    lines.append('static const BoundedCubin bounded_cubins[1][2]={')
    for v in range(1):
        parts=[]
        for p in range(2):
            m=metadata[v*2+p];parts.append('{bounded_cubin_%d_%d,"%s",%d,%d,%d,%d}'%(v,p,m['name'],m['m'],m['n'],m['warps'],m['shared']))
        lines.append('{'+','.join(parts)+'},')
    lines.append('};');out.write_text('\n'.join(lines)+'\n')
    (out.with_suffix('.json')).write_text(json.dumps(dict(generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),kernels=metadata),indent=2)+'\n')
if __name__=='__main__':main()
